package com.reqwise.service.quality;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class LinguisticRuleEngineTest {

    private LinguisticRuleEngine ruleEngine;

    @BeforeEach
    void setUp() {
        ruleEngine = new LinguisticRuleEngine();
    }

    @Test
    @DisplayName("INCOSE-R12: Flags weak modal verbs (should, could, may, might, would)")
    void shouldFlagWeakModals() {
        String text = "The application should validate email addresses, and the user may upload an avatar. The system could notify admins.";
        List<LinguisticFlag> flags = ruleEngine.checkText(text);

        assertThat(flags).isNotEmpty();
        assertThat(flags)
                .filteredOn(f -> "INCOSE-R12".equals(f.ruleId()))
                .extracting(LinguisticFlag::flaggedPhrase)
                .contains("should", "may", "could");
    }

    @Test
    @DisplayName("INCOSE-R07: Flags subjective and unmeasurable terms (fast, scalable, user-friendly, etc.)")
    void shouldFlagVagueTerms() {
        String text = "The system shall be fast, robust, and user-friendly, supporting scalable operations etc.";
        List<LinguisticFlag> flags = ruleEngine.checkText(text);

        assertThat(flags)
                .filteredOn(f -> "INCOSE-R07".equals(f.ruleId()))
                .extracting(f -> f.flaggedPhrase().toLowerCase())
                .contains("fast", "robust", "user-friendly", "scalable", "etc");
    }

    @Test
    @DisplayName("INCOSE-R03: Flags passive voice without an explicit actor")
    void shouldFlagPassiveVoiceWithoutActor() {
        String text = "The invoice must be generated within five seconds.";
        List<LinguisticFlag> flags = ruleEngine.checkText(text);

        assertThat(flags)
                .filteredOn(f -> "INCOSE-R03".equals(f.ruleId()))
                .isNotEmpty();
    }

    @Test
    @DisplayName("INCOSE-R03: Does not flag passive voice when explicit actor is present with 'by'")
    void shouldNotFlagPassiveVoiceWithExplicitActor() {
        String text = "The report shall be generated by BillingService within five seconds.";
        List<LinguisticFlag> flags = ruleEngine.checkText(text);

        assertThat(flags)
                .filteredOn(f -> "INCOSE-R03".equals(f.ruleId()))
                .isEmpty();
    }

    @Test
    @DisplayName("Compliant requirement passes without any INCOSE flags")
    void shouldPassCleanRequirement() {
        String text = "The system shall authenticate user credentials against LDAP directory within 500 milliseconds.";
        List<LinguisticFlag> flags = ruleEngine.checkText(text);

        assertThat(flags).isEmpty();
    }
}
